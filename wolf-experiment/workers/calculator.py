"""Простой калькулятор — два базовых арифметических действия.

Модуль предоставляет функции сложения и умножения для чисел с плавающей
точкой. Используется как базовый пример в эксперименте wolf-experiment.
"""

from __future__ import annotations


def add(a: float, b: float) -> float:
    """Возвращает сумму двух чисел.

    Args:
        a: Первое слагаемое.
        b: Второе слагаемое.

    Returns:
        Результат сложения a и b.
    """
    return a + b


def multiply(a: float, b: float) -> float:
    """Возвращает произведение двух чисел.

    Args:
        a: Первый множитель.
        b: Второй множитель.

    Returns:
        Результат умножения a на b.
    """
    return a * b
