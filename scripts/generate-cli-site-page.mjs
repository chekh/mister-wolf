#!/usr/bin/env node
// REL-2.22.1: полная страница команд сайта из реестра commander (через собранный
// dist). На каждую команду и подкоманду — строка с полным путём и однострочным
// описанием; ссылка на раздел сайта берётся из фактических заголовков уже
// существующих docs/site/guide/cli/*.md (нет заголовка — ссылки нет, не выдумываем).
// Guard-пара: tests/unit/cli-site-page-guard.test.ts (страница == реестр,
// покрытие путей docs/reference/cli.md).
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { format } from 'prettier';

const repoRoot = dirname(dirname(fileURLToPath(import.meta.url)));
const registryJs = join(repoRoot, 'dist/adapters/cli/cli-entry.js');
const siteCliDir = join(repoRoot, 'docs/site/guide/cli');
const MARKER = '<!-- generated by scripts/generate-cli-site-page.mjs — do not edit -->';

function ensureDist() {
  if (existsSync(registryJs)) return;
  throw new Error('generate-cli-site-page: dist/ не собран — запусти npm run build');
}

/** `wolf session wrap-up` → `wolf-session-wrap-up` (VitePress-слагификация заголовков). */
function slug(text) {
  return text
    .toLowerCase()
    .replace(/[^a-z0-9\s-]/g, '')
    .trim()
    .replace(/\s+/g, '-');
}

/** Заголовки `## wolf x y` из существующих страниц раздела → путь команды. */
function sectionAnchors(dir, prefix) {
  const map = new Map();
  for (const page of [
    'overview',
    'memory',
    'sessions-context',
    'work-management',
    'thinking-council',
    'analytics',
    'platform',
  ]) {
    const file = join(dir, `${page}.md`);
    if (!existsSync(file)) continue;
    for (const line of readFileSync(file, 'utf8').split('\n')) {
      const heading = line.match(/^#{2,6}\s+(wolf\s+.+?)\s*$/);
      if (!heading) continue;
      const label = heading[1].replace(/\s*\(hidden\)$/, '');
      const path = label.replace(/^wolf\s+/, '');
      if (!map.has(path)) map.set(path, `${prefix}/guide/cli/${page}#${slug(label)}`);
    }
  }
  return map;
}

async function collect() {
  ensureDist();
  const { COMMANDS } = await import(pathToFileURL(registryJs).href);
  const rows = [];
  const walk = (cmd, path, hidden) => {
    rows.push({ path: path.join(' '), description: cmd.description(), hidden });
    for (const sub of cmd.commands) {
      if (sub.name() === 'help') continue;
      walk(sub, [...path, sub.name()], sub._hidden === true);
    }
  };
  for (const spec of COMMANDS) {
    // hidden-синонимы analytics (§6.5) в реестре без собственной подкоманды
    if (spec.aliasView !== undefined) {
      rows.push({ path: spec.name, description: spec.description, hidden: true, alias: true });
      continue;
    }
    const cmd = await spec.load();
    walk(cmd, [spec.name], spec.hidden === true);
  }
  return rows;
}

function render({ rows, anchors, title, intro }) {
  // VitePress парсит markdown как Vue-шаблон: `<id>` вне inline-code — незакрытый
  // HTML-тег (build падает), `{{` — интерполяция. `|` рвёт ячейку таблицы.
  const cell = (text) =>
    text.replaceAll('&', '&amp;').replaceAll('{{', '&#123;&#123;').replaceAll('|', '\\|').replaceAll('<', '&lt;');
  const lines = [
    MARKER,
    '',
    `# ${title}`,
    '',
    intro,
    '',
    '| Command | What it does | Docs |',
    '| ------- | ------------ | ---- |',
  ];
  for (const row of rows) {
    const link = anchors.get(row.path);
    const marks = row.hidden ? (row.alias ? ' (hidden view alias)' : ' (hidden)') : '';
    lines.push(`| \`wolf ${row.path}\`${marks} | ${cell(row.description)} | ${link ? `[Section](${link})` : '—'} |`);
  }
  return `${lines.join('\n')}\n`;
}

export async function generateSitePages() {
  const rows = await collect();
  const en = render({
    rows,
    anchors: sectionAnchors(siteCliDir, ''),
    title: 'Command Reference',
    intro:
      'Every `wolf` command path from the CLI registry, generated by `scripts/generate-cli-site-page.mjs` — visible and hidden plumbing alike. Hidden commands are marked `(hidden)`; the three `analytics` view aliases appear as `(hidden view alias)` because they are view names rather than their own command, which is why this table has more rows than the reference has headings. `Section` points to the page that documents the command in depth. Hand edits are useless: `tests/unit/cli-site-page-guard.test.ts` compares this file with the registry. Regenerate with `node scripts/generate-cli-site-page.mjs` (same step runs in `npm run docs:build`).',
  });
  const ru = render({
    rows,
    anchors: sectionAnchors(join(repoRoot, 'docs/site/ru/guide/cli'), '/ru'),
    title: 'Справочник команд',
    intro:
      'Все полные пути команд `wolf` из реестра CLI, генерируются `scripts/generate-cli-site-page.mjs` — включая скрытые plumbing-команды. Скрытые помечены `(hidden)`, три алиаса-представления `analytics` помечены `(hidden view alias)`: это имена представлений, а не собственные команды, поэтому строк в таблице больше, чем заголовков в справочнике. `Section` ведёт на страницу раздела с подробным описанием. Описания команд приведены на английском — в том же виде, что в справочнике и `--help`. Ручные правки бесполезны: `tests/unit/cli-site-page-guard.test.ts` сверяет файл с реестром. Регенерация: `node scripts/generate-cli-site-page.mjs` (то же делает `npm run docs:build`).',
  });
  const enFile = join(repoRoot, 'docs/site/guide/cli/command-reference.md');
  const ruFile = join(repoRoot, 'docs/site/ru/guide/cli/command-reference.md');
  return {
    en: await format(en, { filepath: enFile }),
    ru: await format(ru, { filepath: ruFile }),
  };
}

const isMain = process.argv[1] !== undefined && import.meta.url === pathToFileURL(process.argv[1]).href;
if (isMain) {
  // Prettier-нормализация вывода: format:check гоняет docs/**/*.md (см. sync-changelog.mjs).
  const pages = await generateSitePages();
  const enFile = join(repoRoot, 'docs/site/guide/cli/command-reference.md');
  const ruFile = join(repoRoot, 'docs/site/ru/guide/cli/command-reference.md');
  writeFileSync(enFile, pages.en);
  writeFileSync(ruFile, pages.ru);
  console.log(`generate-cli-site-page: ${enFile} + ru mirror regenerated`);
}
