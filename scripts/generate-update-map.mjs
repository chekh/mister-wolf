#!/usr/bin/env node
// scripts/generate-update-map.mjs
// T1 (волна 2.19.0, ADR-1): генератор скелета update-map.json — полный
// инвентарь файловых целей синка (те же корни, что templateFiles() в
// src/adapters/render/opencode/opencode-renderer.ts), шаблоны базовых лиц
// и AGENTS.md-блок. Категории new/changed/unchanged/removed вычислимы из
// diff prev→cur (git-тег v<prev>); deprecated — ручная курированная
// категория: переносится из существующей карты как есть, TODO — только в
// консоль, НЕ в JSON.
// Режимы: (без флагов) запись скелета; --dry-run — печать без записи;
// --verify — самопроверка согласованности карты с templates/ (рассинхрон
// → exit 1, REQ-12: релиз с непрошедшей самопроверкой не выходит).
// Guard-пара: tests/unit/adapters/update-map.test.ts.
import { execFileSync } from 'node:child_process';
import { existsSync, readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const repoRoot = dirname(dirname(fileURLToPath(import.meta.url)));

// Корни файловых целей синка: каталог templates/ → kind карты (дословно
// по NEUTRAL_DIRS/LAYOUT рендерера + harness-плагины NC1).
const FILE_DIRS = [
  { dir: 'base/agents', kind: 'agent' },
  { dir: 'base/skills', kind: 'skill' },
  { dir: 'base/commands', kind: 'command' },
  { dir: 'opencode/plugins', kind: 'plugin' },
];
const PLAYBOOKS_DIR = 'base/playbooks';
const AGENTS_MD = 'base/AGENTS.md';

// Классы вне покрытия v1 (requirements REQ-10): граница «не трогать чужое»
// объявлена явно. Курировать здесь при расширении покрытия.
const OUTSIDE_V1 = [
  'taxonomy (config.yaml memory_types — manual wolf taxonomy)',
  'tool-skills (generated by wolf tool — not a base-set path)',
  'local/foreign artifacts (untracked .opencode/* and .wolf/* files)',
];

function* walk(dir) {
  if (!existsSync(dir)) return;
  for (const e of readdirSync(dir)) {
    const p = join(dir, e);
    if (statSync(p).isDirectory()) yield* walk(p);
    else yield p;
  }
}

/** Полный состав файловых целей синка: path относительно templates/ + kind. */
export function syncTargets(templatesRoot) {
  const out = [];
  for (const { dir, kind } of FILE_DIRS) {
    for (const p of walk(join(templatesRoot, dir))) out.push({ path: relative(templatesRoot, p), kind });
  }
  return out.sort((a, b) => a.path.localeCompare(b.path));
}

/** Шаблоны базовых лиц: template (относительно templates/) + owner_skill из frontmatter. */
export function faceTemplates(templatesRoot) {
  return [...walk(join(templatesRoot, PLAYBOOKS_DIR))]
    .map((p) => ({
      template: relative(templatesRoot, p),
      owner_skill: parseOwnerSkill(readFileSync(p, 'utf8')),
    }))
    .sort((a, b) => a.template.localeCompare(b.template));
}

function parseOwnerSkill(raw) {
  const m = raw.match(/^owner_skill:\s*(.+)$/m);
  return m ? m[1].trim() : '';
}

const sortedPaths = (iterable) => [...iterable].sort((a, b) => a.localeCompare(b));

/** kind по префиксу пути (для removed-целей из prev, которых уже нет на диске). */
function kindForPath(path) {
  return FILE_DIRS.find(({ dir }) => path === dir || path.startsWith(`${dir}/`))?.kind ?? null;
}

function isMapPath(path) {
  return kindForPath(path) !== null || path.startsWith(`${PLAYBOOKS_DIR}/`) || path === AGENTS_MD;
}

function compareSemver(a, b) {
  const pa = a.split('.').map(Number);
  const pb = b.split('.').map(Number);
  for (let i = 0; i < 3; i++) {
    if (pa[i] !== pb[i]) return pa[i] < pb[i] ? -1 : 1;
  }
  return 0;
}

function git(args, opts = {}) {
  return execFileSync('git', args, { encoding: 'utf8', maxBuffer: 8 * 1024 * 1024, ...opts });
}

/**
 * Снимок templates/ на теге v<prev>: Map<path, content|null>. Только пути,
 * относящиеся к карте (цели синка, playbooks, AGENTS.md).
 */
export function defaultPrevIndex(prev) {
  try {
    git(['rev-parse', '-q', '--verify', `refs/tags/v${prev}`], { stdio: 'pipe' });
  } catch {
    throw new Error(`generate-update-map: tag v${prev} not found — pass a valid --prev X.Y.Z`);
  }
  const list = git(['ls-tree', '-r', '--name-only', `v${prev}`, '--', 'templates/'])
    .split('\n')
    .filter(Boolean);
  const index = new Map();
  for (const repoPath of list) {
    const rel = repoPath.slice('templates/'.length);
    if (!isMapPath(rel)) continue;
    let content = null;
    try {
      content = git(['show', `v${prev}:${repoPath}`]);
    } catch {
      // файла нет в prev → new
    }
    index.set(rel, content);
  }
  return index;
}

function parseSchemaVersion(raw) {
  const m = raw.match(/CURRENT_SCHEMA_VERSION\s*=\s*(\d+)/);
  return m ? Number(m[1]) : null;
}

/** Миграции схемы: diff CURRENT_SCHEMA_VERSION у тега prev и в рабочем дереве. */
export function detectSchemaMigrations(prev) {
  const cur = parseSchemaVersion(readFileSync(join(repoRoot, 'src/adapters/fs/schema-version.ts'), 'utf8'));
  let was = null;
  try {
    was = parseSchemaVersion(git(['show', `v${prev}:src/adapters/fs/schema-version.ts`]));
  } catch {
    // файла/тега нет — миграций не видим
  }
  if (cur === null || was === null || cur === was) return [];
  return [{ from: was, to: cur }];
}

/**
 * Скелет карты. opts: { version, prev, templatesRoot, prevIndex?, existing?,
 * schemaMigrations? } — prevIndex/existing/schemaMigrations инжектятся
 * тестами (контур без git); дефолты — git-тег и файлы репо.
 * Возвращает { map, todos } — todos только для консоли, не для JSON.
 */
export function buildUpdateMap(opts) {
  const { version, prev, templatesRoot } = opts;
  const prevIndex = opts.prevIndex ?? defaultPrevIndex(prev);
  const existing = opts.existing ?? readExisting(repoRoot);
  const schemaMigrations = opts.schemaMigrations !== undefined ? opts.schemaMigrations : detectSchemaMigrations(prev);
  const todos = [];
  const cur = (rel) => readFileSync(join(templatesRoot, rel), 'utf8');
  const diffCategory = (rel) => {
    const was = prevIndex.get(rel) ?? null;
    return was === null ? 'new' : was === cur(rel) ? 'unchanged' : 'changed';
  };
  const findExisting = (list, key, value) => (list ?? []).find((e) => e[key] === value);

  const files = [];
  for (const t of syncTargets(templatesRoot)) {
    let category = diffCategory(t.path);
    if (findExisting(existing?.files, 'path', t.path)?.category === 'deprecated') {
      category = 'deprecated';
      todos.push(`files[${t.path}]: deprecated (curated) — stays in delivery, reported, not mutated`);
    }
    files.push({ path: t.path, kind: t.kind, category });
  }
  // removed: есть в prev, нет в текущих templates/ (деприкация вручную поверх
  // removed не имеет смысла — deprecated-цель обязана оставаться в поставке)
  const currentPaths = new Set(files.map((f) => f.path));
  for (const p of sortedPaths(prevIndex.keys())) {
    if (currentPaths.has(p) || kindForPath(p) === null) continue;
    files.push({ path: p, kind: kindForPath(p), category: 'removed' });
  }
  files.sort((a, b) => a.path.localeCompare(b.path));

  const faces = [];
  const seen = new Set();
  for (const f of faceTemplates(templatesRoot)) {
    let category = diffCategory(f.template);
    let seed = true;
    if (findExisting(existing?.faces, 'template', f.template)?.category === 'deprecated') {
      category = 'deprecated';
      seed = false;
      todos.push(`faces[${f.template}]: deprecated (curated) — reported, not mutated`);
    }
    if (f.owner_skill === '') todos.push(`faces[${f.template}]: no owner_skill in frontmatter — fix the template`);
    faces.push({ template: f.template, owner_skill: f.owner_skill, category, seed });
    seen.add(f.template);
  }
  // REQ-11: шаблон лица удалён из base-set → deprecated seed:false (живые лица
  // репортятся, не мутируются). Источники: prev-тег + курируемая карта.
  const absent = new Set([
    ...sortedPaths(prevIndex.keys()).filter((p) => p.startsWith(`${PLAYBOOKS_DIR}/`) && !seen.has(p)),
    ...(existing?.faces ?? []).filter((e) => e.category === 'deprecated').map((e) => e.template),
  ]);
  for (const p of absent) {
    if (seen.has(p) || faces.some((e) => e.template === p)) continue;
    const was = prevIndex.get(p);
    faces.push({
      template: p,
      owner_skill: was ? parseOwnerSkill(was) : (findExisting(existing?.faces, 'template', p)?.owner_skill ?? ''),
      category: 'deprecated',
      seed: false,
    });
    todos.push(`faces[${p}]: template removed — deprecated face, report-only`);
  }
  faces.sort((a, b) => a.template.localeCompare(b.template));

  return {
    map: {
      version,
      prev,
      files,
      faces,
      agents_md: { category: diffCategory(AGENTS_MD), mode: 'append-block' },
      schema_migrations: schemaMigrations,
      outside_v1: OUTSIDE_V1,
    },
    todos,
  };
}

function readExisting(root) {
  const p = join(root, 'update-map.json');
  if (!existsSync(p)) return null;
  try {
    return JSON.parse(readFileSync(p, 'utf8'));
  } catch {
    console.error('generate-update-map: existing update-map.json is not valid JSON — deprecated curation ignored');
    return null;
  }
}

/**
 * Инварианты карты ↔ templates/ (design §«Карта»): неп-removed файлы
 * существуют и являются целями синка; removed — отсутствуют; все цели
 * синка и все playbook-шаблоны покрыты; deprecated лица не сеют.
 * Согласование с package.json — при переданном repoRoot.
 */
export function verifyMap(map, templatesRoot, rootForPackageJson) {
  const problems = [];
  const targets = new Set(syncTargets(templatesRoot).map((t) => t.path));
  const mapped = new Set();
  for (const f of map.files ?? []) {
    const exists = targets.has(f.path);
    if (f.category === 'removed') {
      if (exists) problems.push(`files[${f.path}]: removed but still present in templates/`);
      const expected = kindForPath(f.path);
      if (expected !== null && expected !== f.kind) {
        problems.push(`files[${f.path}]: kind '${f.kind}' != actual '${expected}'`);
      }
      continue;
    }
    if (!exists) problems.push(`files[${f.path}]: ${f.category} but missing from templates/`);
    mapped.add(f.path);
    const expected = kindForPath(f.path);
    if (expected !== f.kind) problems.push(`files[${f.path}]: kind '${f.kind}' != actual '${expected}'`);
  }
  for (const t of targets) {
    if (!mapped.has(t)) problems.push(`files: sync target '${t}' not covered by update-map.json`);
  }
  const liveFaces = new Set(faceTemplates(templatesRoot).map((f) => f.template));
  for (const e of map.faces ?? []) {
    if (e.category === 'deprecated' && e.seed) {
      problems.push(`faces[${e.template}]: deprecated face must not seed (report-only)`);
    }
    if (e.category !== 'deprecated' && !liveFaces.has(e.template)) {
      problems.push(`faces[${e.template}]: ${e.category} but template missing from templates/`);
    }
  }
  for (const t of liveFaces) {
    if (!(map.faces ?? []).some((e) => e.template === t)) {
      problems.push(`faces: playbook template '${t}' not covered by update-map.json`);
    }
  }
  if (rootForPackageJson) {
    const pkg = JSON.parse(readFileSync(join(rootForPackageJson, 'package.json'), 'utf8'));
    if (pkg.version !== map.version) {
      problems.push(
        `version ${map.version} != package.json ${pkg.version} — run: node scripts/generate-update-map.mjs`
      );
    }
  }
  return { ok: problems.length === 0, problems };
}

/** Ближайший предыдущий тег v2.* строго ниже version (локальный git, без сети). */
function nearestPrevTag(version) {
  let tags;
  try {
    tags = git(['tag', '-l', 'v*']).split('\n').filter(Boolean);
  } catch {
    return null;
  }
  const below = tags
    .map((t) => t.replace(/^v/, ''))
    .filter((v) => /^\d+\.\d+\.\d+$/.test(v) && compareSemver(v, version) < 0);
  if (below.length === 0) return null;
  return below.sort(compareSemver).at(-1);
}

function main() {
  const argv = process.argv.slice(2);
  const get = (name) => {
    const i = argv.indexOf(`--${name}`);
    return i !== -1 ? argv[i + 1] : undefined;
  };
  if (argv.includes('--verify')) {
    const p = join(repoRoot, 'update-map.json');
    if (!existsSync(p)) {
      console.error(`generate-update-map: ${p} not found — run: node scripts/generate-update-map.mjs`);
      process.exit(1);
    }
    const map = JSON.parse(readFileSync(p, 'utf8'));
    const r = verifyMap(map, join(repoRoot, 'templates'), repoRoot);
    if (!r.ok) {
      for (const problem of r.problems) console.error(`generate-update-map: ${problem}`);
      console.error('update-map.json is out of sync with templates/ — run: node scripts/generate-update-map.mjs');
      process.exit(1);
    }
    console.log(
      `update-map.json is in sync with templates/ (${map.files.length} file targets, ${map.faces.length} faces, prev ${map.prev})`
    );
    return;
  }
  const version = JSON.parse(readFileSync(join(repoRoot, 'package.json'), 'utf8')).version;
  const prev = get('prev') ?? nearestPrevTag(version);
  if (!prev || !/^\d+\.\d+\.\d+$/.test(prev)) {
    console.error('generate-update-map: cannot resolve prev release — pass --prev X.Y.Z');
    process.exit(1);
  }
  const { map, todos } = buildUpdateMap({ version, prev, templatesRoot: join(repoRoot, 'templates'), repoRoot });
  const json = `${JSON.stringify(map, null, 2)}\n`;
  if (argv.includes('--dry-run')) {
    console.log(json.trimEnd());
  } else {
    writeFileSync(join(repoRoot, 'update-map.json'), json);
    const counts = {};
    for (const f of map.files) counts[f.category] = (counts[f.category] ?? 0) + 1;
    console.log(
      `update-map.json: version ${version}, prev ${prev}, ` +
        `${map.files.length} files (${Object.entries(counts)
          .map(([k, v]) => `${v} ${k}`)
          .join(', ')}), ` +
        `${map.faces.length} faces, schema_migrations ${JSON.stringify(map.schema_migrations)}`
    );
  }
  for (const todo of todos) console.log(`TODO ${todo}`);
}

const isMain = process.argv[1] !== undefined && import.meta.url === pathToFileURL(process.argv[1]).href;
if (isMain) {
  main();
}
