#!/usr/bin/env node
// P224 (спека 2.13 §6.6): docs/reference/cli.md генерируется из реестра
// commander (COMMANDS в src/adapters/cli/cli-entry.ts, через собранный dist) —
// ручных строк 0. На каждую команду (включая hidden-plumbing) — фактический
// вывод `wolf <path> --help`; скрытые синонимы §6.5 — строками-ссылками.
// Guard-пара: tests/unit/cli-reference-guard.test.ts (справочник == реестр).
import { execFileSync, spawnSync } from 'node:child_process';
import { existsSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const repoRoot = dirname(dirname(fileURLToPath(import.meta.url)));
const cliJs = join(repoRoot, 'dist/bootstrap/cli.js');
const registryJs = join(repoRoot, 'dist/adapters/cli/cli-entry.js');
const MARKER = '<!-- generated by scripts/generate-cli-reference.mjs — do not edit -->';

function ensureDist() {
  if (existsSync(cliJs) && existsSync(registryJs)) return;
  console.error('generate-cli-reference: dist/ не собран — запускаю npm run build…');
  const r = spawnSync('npm', ['run', 'build'], { cwd: repoRoot, stdio: 'inherit' });
  if (r.status !== 0) throw new Error('generate-cli-reference: npm run build failed');
}

/** Фактический help собранного CLI по полному пути команды (`session wrap-up`). */
function helpText(path) {
  return execFileSync('node', [cliJs, ...path, '--help'], {
    encoding: 'utf8',
    maxBuffer: 8 * 1024 * 1024,
  }).replace(/\n+$/, '');
}

/** Дерево подкоманд реальной команды. Скрытость — приватное `_hidden`
 * (публичного геттера в commander 12 нет); неявный `help` в .commands не
 * лежит, но фильтруем и по имени на случай будущих версий. */
function subcommands(cmd, path) {
  return cmd.commands
    .filter((sub) => sub.name() !== 'help')
    .map((sub) => {
      const p = [...path, sub.name()];
      return { name: sub.name(), hidden: sub._hidden === true, path: p, subs: subcommands(sub, p) };
    });
}

function renderCommand(node, depth) {
  const heading = `${'#'.repeat(Math.min(3 + depth, 6))} wolf ${node.path.join(' ')}${node.hidden ? ' (hidden)' : ''}`;
  const out = [heading, '', '```text', helpText(node.path), '```', ''];
  for (const sub of node.subs) out.push(...renderCommand(sub, depth + 1));
  return out;
}

export async function generateReference() {
  ensureDist();
  const { COMMANDS } = await import(pathToFileURL(registryJs).href);
  const visible = [];
  const hidden = [];
  const synonyms = [];
  for (const spec of COMMANDS) {
    // Синонимы §6.5 — не самостоятельные команды: строка-ссылка вместо секции
    if (spec.aliasView !== undefined) {
      synonyms.push(`- \`wolf ${spec.name}\` — скрытый синоним: \`analytics --view ${spec.aliasView}\``);
      continue;
    }
    const node = {
      name: spec.name,
      hidden: spec.hidden === true,
      path: [spec.name],
      subs: subcommands(await spec.load(), [spec.name]),
    };
    (node.hidden ? hidden : visible).push(node);
  }

  const lines = [
    MARKER,
    '',
    '# CLI Reference',
    '',
    'Справочник генерируется скриптом `scripts/generate-cli-reference.mjs` из реестра commander (`src/adapters/cli/cli-entry.ts`): на каждую команду — фактический вывод `wolf <path> --help` собранного CLI. Ручные правки файла бесполезны: guard-тест `tests/unit/cli-reference-guard.test.ts` сверяет файл с реестром.',
    '',
    'Регенерация: `node scripts/generate-cli-reference.mjs` (то же делает `npm run docs:build`).',
    '',
    '## Команды',
    '',
  ];
  for (const node of visible) lines.push(...renderCommand(node, 0));
  lines.push(
    '## Скрытые команды (plumbing)',
    '',
    'Скрыты из `wolf --help` (бюджет ≤ 30 строк, спека 2.13 §6.6), но работают как обычные команды.',
    ''
  );
  for (const node of hidden) lines.push(...renderCommand(node, 0));
  if (synonyms.length > 0) {
    lines.push('### Скрытые синонимы analytics (§6.5)', '', ...synonyms, '');
  }
  return `${lines.join('\n').replace(/\n+$/, '')}\n`;
}

const isMain = process.argv[1] !== undefined && import.meta.url === pathToFileURL(process.argv[1]).href;
if (isMain) {
  const target = join(repoRoot, 'docs/reference/cli.md');
  writeFileSync(target, await generateReference());
  console.log(`generate-cli-reference: ${target} regenerated`);
}
